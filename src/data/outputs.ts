export const OUTPUT = Object.fromEntries(OUTPUTS.map((o) => [o.id, o])) as Record<string, Output>;
export const childrenOf = (id: string) => OUTPUTS.filter((o) => o.derivedFrom === id);

/** מקור של עובדה: אמירה, מחלוקת, ממצא מחקר או כתבה. אחרת null, והבדיקה נכשלת */
export type RefInfo = { kind: 'saying' | 'idea' | 'research' | 'article'; label: string; page: string; params: Record<string, string> };
export function refInfo(id: string): RefInfo | null {
  if (id.startsWith('idea:')) { const i = IDEA[id.slice(5)]; return i ? { kind: 'idea', label: i.q, page: 'daf', params: { i: i.id } } : null; }
  if (id.startsWith('research:')) { const f = FINDING[id.slice(9)]; return f ? { kind: 'research', label: f.title, page: 'research', params: { x: f.id } } : null; }
  if (id.startsWith('article:')) { const a = ARTICLES.find((x) => x.id === id.slice(8)); return a ? { kind: 'article', label: a.title, page: 'article', params: { a: a.id } } : null; }
  const s = BY_ID[id];
  return s ? { kind: 'saying', label: s.nikud || s.he, page: 'daf', params: { i: s.idea, s: s.id } } : null;
}

export const claudeUrl = (prompt: string) => `https://claude.ai/new?q=${encodeURIComponent(prompt)}`;

/** פרומפט ל-Claude: הסוג, המנגנון, והחומר שממנו כותבים (תוצר קודם, או טקסט עם ראיות) */
export function buildOutputPrompt(kind: Kind, material: { from?: Output; text?: string; evidence?: string[] }) {
  const parts = [KIND[kind].prompt];
  if (material.from) {
    const f = material.from;
    parts.push(`התוצר הזה מתפתח מ${KIND[f.kind].name}: "${f.title}". השאלה שהיא השאירה: ${f.question}`);
    parts.push(`החומר מהתוצר הקודם, עם רמות הידע שלו:\n${f.blocks.map((b) => `- [${LEVEL_NAME[b.level]}] ${b.text.replace(/\*\*|==/g, '')}`).join('\n')}`);
    parts.push('שמור על המקורות של התוצר הקודם, וציין בראש התוצר החדש ממה הוא התפתח.');
  }
  if (material.text) parts.push(`החומר:\n${material.text}`);
  if (material.evidence?.length) parts.push(`המקורות באטלס "אמירות":\n${material.evidence.join('\n')}`);
  parts.push('כתוב בעברית. הפרד בבירור בין עובדה מבוססת, פרשנות, השערה ודמיון.');
  return parts.join('\n\n');
}
